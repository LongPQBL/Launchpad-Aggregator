#!/usr/bin/env python3
"""Export the Envio Cloud seed allowlists and render three bounded Cloud configs.

The seed GraphQL URL is passed on the command line; no deploy-time environment
variables are needed. Pool allowlists are generated from the completed seed
deployment so all window indexers share the same source of truth.
"""

import argparse
import json
import os
import ssl
import time
import urllib.error
import urllib.request
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CHAIN_ID = 4663
START_BLOCK = 8_600_612
WINDOW_SIZE = 10_000_000
WINDOW_COUNT = 3
PONS_V2_FACTORY_START = 26_841_846
PAGE_SIZE = 1000
SSL_CONTEXT = ssl.create_default_context(cafile=os.environ.get("SSL_CERT_FILE") or "/etc/ssl/cert.pem")
SEED_SOURCE = ROOT / "config.yaml"
GENERATED_SEED = ROOT / "src/seeded-cloud-pools.generated.ts"
OUTPUT_PREFIX = "config.cloud.seeded-window"


def graphql(url: str, query: str) -> dict:
    request = urllib.request.Request(
        url,
        data=json.dumps({"query": query}).encode(),
        headers={"content-type": "application/json"},
    )
    for attempt in range(6):
        try:
            with urllib.request.urlopen(request, timeout=60, context=SSL_CONTEXT) as response:
                payload = json.loads(response.read())
            if payload.get("errors"):
                raise RuntimeError("Seed GraphQL error: " + "; ".join(
                    error.get("message", "unknown") for error in payload["errors"]
                ))
            return payload["data"]
        except urllib.error.HTTPError as error:
            if error.code != 429 and error.code < 500:
                raise RuntimeError(f"Seed GraphQL returned HTTP {error.code}") from None
            if attempt == 5:
                raise RuntimeError(f"Seed GraphQL returned HTTP {error.code} after retries") from None
            time.sleep(min(30, 2 ** attempt))
    raise RuntimeError("Seed GraphQL did not return a response")


def fetch_rows(url: str, entity: str, fields: str, where: str) -> list[dict]:
    rows: list[dict] = []
    after_id = ""
    while True:
        id_filter = f",id:{{_gt:{json.dumps(after_id)}}}" if after_id else ""
        query = (
            f"query SeedPage {{ {entity}(where:{{{where}{id_filter}}},"
            f"order_by:{{id:asc}},limit:{PAGE_SIZE}) {{ {fields} }} }}"
        )
        page = graphql(url, query)[entity]
        rows.extend(page)
        print(f"{entity}: fetched {len(rows):,}", flush=True)
        if len(page) < PAGE_SIZE:
            return rows
        next_id = page[-1]["id"]
        if next_id <= after_id:
            raise RuntimeError(f"{entity} pagination did not advance")
        after_id = next_id


def write_generated_seed(url: str, seed_end: int) -> list[dict]:
    meta = graphql(url, "query SeedMeta { _meta { chainId progressBlock isReady } }")["_meta"]
    meta = next((row for row in meta if row["chainId"] == CHAIN_ID), None)
    if not meta or not meta["isReady"] or int(meta["progressBlock"]) < seed_end:
        raise RuntimeError(f"Seed deployment is not ready through block {seed_end}")

    kinds = ["uniswap_v2", "uniswap_v3", "uniswap_v4"]
    kind_filter = json.dumps(kinds)
    max_block = json.dumps(str(seed_end))
    pools = fetch_rows(
        url, "SeededPool", "id kind poolAddress blockNumber",
        f"chainId:{{_eq:{CHAIN_ID}}},kind:{{_in:{kind_filter}}},blockNumber:{{_lte:{max_block}}}",
    )
    rows = sorted((
        {"kind": row["kind"], "poolAddress": row["poolAddress"].lower(),
         "blockNumber": int(row["blockNumber"])} for row in pools
    ), key=lambda row: (row["blockNumber"], row["kind"], row["poolAddress"]))
    content = (
        "// Generated by scripts/build-cloud-seed-windows.py; do not edit by hand.\n"
        "export interface SeededCloudPools {\n"
        "  uniswapV2Pairs: readonly string[];\n"
        "  uniswapV3Pools: readonly string[];\n"
        "  uniswapV4PoolIds: readonly string[];\n"
        "}\n"
        f"const seedRows = {json.dumps(rows, separators=(',', ':'))} as const;\n"
        "export function seedPoolsThrough(endBlock: number): SeededCloudPools {\n"
        "  const rows = seedRows.filter((row) => row.blockNumber <= endBlock);\n"
        "  return {\n"
        "    uniswapV2Pairs: rows.filter((row) => row.kind === 'uniswap_v2').map((row) => row.poolAddress),\n"
        "    uniswapV3Pools: rows.filter((row) => row.kind === 'uniswap_v3').map((row) => row.poolAddress),\n"
        "    uniswapV4PoolIds: rows.filter((row) => row.kind === 'uniswap_v4').map((row) => row.poolAddress),\n"
        "  };\n"
        "}\n"
    )
    GENERATED_SEED.write_text(content)
    for index in range(WINDOW_COUNT):
        end = START_BLOCK + (index + 1) * WINDOW_SIZE - 1
        selected = [row for row in rows if row["blockNumber"] <= end]
        print(f"Seed through {end:,}: " + ", ".join(
            f"{kind}={sum(row['kind'] == kind for row in selected):,}"
            for kind in kinds
        ), flush=True)
    return rows


def render_configs(seed_rows: list[dict]) -> None:
    base = yaml.safe_load(SEED_SOURCE.read_text())
    chain = next(row for row in base["chains"] if row["id"] == CHAIN_ID)
    for index in range(WINDOW_COUNT):
        start = START_BLOCK + index * WINDOW_SIZE
        end = start + WINDOW_SIZE - 1
        config = json.loads(json.dumps(base))
        config["name"] = f"pons-envio-cloud-seeded-window-{index + 1}"
        chain_config = next(row for row in config["chains"] if row["id"] == CHAIN_ID)
        # Replay only the two Pons factories on each endpoint so dynamically
        # registered Pons pools/curves created in earlier slices stay discoverable.
        # Every output handler drops rows earlier than this endpoint's target slice.
        chain_config["start_block"] = START_BLOCK
        chain_config["end_block"] = end
        chain_config.pop("rpc", None)

        selected = [row for row in seed_rows if row["blockNumber"] <= end]
        pool_addresses = {
            "UniswapV2Pair": sorted({row["poolAddress"] for row in selected if row["kind"] == "uniswap_v2"}),
            "UniswapV3Pool": sorted({row["poolAddress"] for row in selected if row["kind"] == "uniswap_v3"}),
        }
        for name, addresses in pool_addresses.items():
            next(row for row in chain_config["contracts"] if row["name"] == name)["address"] = addresses

        # Replay Pons launch factories from their deployment blocks, but start all
        # swap/factory/Chainlink sources at the slice boundary.
        for row in chain_config["contracts"]:
            name = row["name"]
            if name == "PonsV1LegacyFactory":
                row["start_block"] = START_BLOCK
            elif name == "PonsV1ActiveFactory":
                row["start_block"] = 8_991_118
            elif name == "PonsV2Factory":
                row["start_block"] = min(end, PONS_V2_FACTORY_START)
            else:
                row["start_block"] = start

        handler_path = f"src/EventHandlersSeededWindow{index + 1}.ts"
        for contract in config["contracts"]:
            contract["handler"] = handler_path

        (ROOT / "src" / f"EventHandlersSeededWindow{index + 1}.ts").write_text(
            "import { registerEventHandlers } from \"./EventHandlersCore\";\n"
            "import { seedPoolsThrough } from \"./seeded-cloud-pools.generated\";\n\n"
            f"registerEventHandlers(\"cloud\", {start}n, seedPoolsThrough({end}));\n"
        )

        output = ROOT / f"{OUTPUT_PREFIX}-{index + 1}.yaml"
        output.write_text(yaml.safe_dump(config, sort_keys=False, width=120))
        print(f"Wrote {output.name}: blocks {start:,}-{end:,}", flush=True)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--graphql-url", required=True)
    args = parser.parse_args()
    seed_end = START_BLOCK + WINDOW_SIZE * WINDOW_COUNT - 1
    seed = write_generated_seed(args.graphql_url, seed_end)
    render_configs(seed)


if __name__ == "__main__":
    main()
